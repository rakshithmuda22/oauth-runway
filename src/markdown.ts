// Guide -> Markdown, for pasting into a PR, a Notion page or a ticket, and for
// agents that would rather read text than JSON (GET /api/guides/<slug>.md).

import type { StoredGuide } from "./types.ts";

const TIER_LABEL: Record<string, string> = {
  "self-serve": "Self-serve",
  "self-serve-with-review": "Self-serve, review to go wide",
  "approval-gated": "Approval-gated",
  "partner-only": "Partner / paid tier only",
};
const OWNER_LABEL: Record<string, string> = { agent: "Agent", "agent+you": "Agent + you", you: "You", provider: "Provider" };
const STATUS_ICON: Record<string, string> = { pass: "✅", info: "ℹ️", fail: "❌" };

const cite = (ids: string[]) => (ids.length ? " " + ids.map((id) => `[${id}]`).join("") : "");
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function tierLabel(tier: string): string {
  return TIER_LABEL[tier] ?? tier;
}

export function toMarkdown(g: StoredGuide, url?: string): string {
  const v = g.verdict;
  const out: string[] = [];
  out.push(`# ${g.app.name}: OAuth app setup and approval`);
  out.push("");
  out.push(`> ${v.headline}`);
  out.push("");
  out.push(`**${tierLabel(v.tier)}** · difficulty ${v.difficulty}/5 · confidence ${v.confidence}${url ? ` · [live version](${url})` : ""}`);
  out.push("");
  out.push("| | |", "|---|---|");
  out.push(`| Time to first connection | ${cell(v.time_to_first_connection)} |`);
  out.push(`| Hands-on effort | ${cell(v.hands_on_effort)} |`);
  out.push(`| Approval wait | ${cell(v.approval_wait)} |`);
  out.push(`| Time to production | ${cell(v.time_to_production)} |`);
  out.push(`| Cost | ${cell(v.cost)} |`);
  out.push(`| Composio managed OAuth | ${g.composio.managed_oauth}${g.composio.toolkit_slug ? ` (\`${g.composio.toolkit_slug}\`)` : ""} |`);
  out.push("");
  out.push(v.summary, "");
  if (g.composio.note) out.push(`**Composio:** ${g.composio.note}`, "");

  out.push("## Steps", "");
  let n = 0;
  for (const p of g.phases) {
    out.push(`### ${p.name}${p.is_wait ? " ⏳" : ""} (${p.duration})`, "", `_${p.goal}_`, "");
    for (const s of p.steps) {
      n++;
      out.push(`${n}. **${s.title}** (${OWNER_LABEL[s.owner] ?? s.owner})${cite(s.sources)}`);
      out.push(`   ${s.detail}`);
      if (s.agent_help) out.push(`   - Agent: ${s.agent_help}`);
      if (s.link) out.push(`   - Link: ${s.link}`);
    }
    out.push("");
  }

  out.push("## What an agent can do vs. what you must do", "");
  out.push("**Agent can:**", ...g.agent_handoff.agent_can.map((x) => `- ${x}`), "");
  out.push("**You must:**", ...g.agent_handoff.you_must.map((x) => `- ${x}`), "");

  if (g.requirements.length) {
    out.push("## Requirements", "", "| Requirement | Needed for | Detail |", "|---|---|---|");
    for (const r of g.requirements) out.push(`| ${cell(r.item)} | ${r.needed_for} | ${cell(r.detail)}${cite(r.sources)} |`);
    out.push("");
  }
  if (g.scopes.length) {
    out.push("## Scopes an agent typically needs", "", "| Scope | Purpose | Sensitivity | Review impact |", "|---|---|---|---|");
    for (const s of g.scopes) out.push(`| \`${cell(s.scope)}\` | ${cell(s.purpose)} | ${s.sensitivity} | ${cell(s.review_impact)}${cite(s.sources)} |`);
    out.push("");
  }
  if (g.limits.length) {
    out.push("## Limits before approval", "");
    for (const l of g.limits) out.push(`- **${l.limit}** (${l.applies_when}). To lift: ${l.how_to_lift}${cite(l.sources)}`);
    out.push("");
  }
  if (g.blockers.length) {
    out.push("## If you get stuck", "");
    for (const b of g.blockers) out.push(`- **${b.blocker}**: you see "${b.symptom}". Fix: ${b.fix}${cite(b.sources)}`);
    out.push("");
  }

  const o = g.oauth;
  out.push("## OAuth details", "");
  out.push(`- Authorize URL: ${o.authorize_url}`, `- Token URL: ${o.token_url}`);
  if (o.discovery_url) out.push(`- Metadata: ${o.discovery_url}`);
  out.push(`- PKCE: ${o.pkce}`, `- Refresh tokens: ${o.refresh_tokens}`, `- Redirect URIs: ${o.redirect_uri_rules}${cite(o.sources)}`, "");

  out.push("## Evidence", "");
  out.push(`### Tested (${g.meta.tested_at.slice(0, 10)})`, "");
  for (const t of g.tested) out.push(`- ${STATUS_ICON[t.status] ?? ""} ${t.check}: ${t.result}`);
  out.push("", "### Sources", "");
  for (const s of g.sources) out.push(`- [${s.id}] [${s.title}](${s.url}) (${s.kind}). Supports: ${s.supports}`);
  if (g.uncertain.length) {
    out.push("", "### Uncertain", "");
    for (const u of g.uncertain) out.push(`- ${u}`);
  }
  out.push("", `---`, `Researched by ${g.meta.researched_by} on ${g.meta.researched_at.slice(0, 10)}. Generated by OAuth Runway.`, "");
  return out.join("\n");
}
